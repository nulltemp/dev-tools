import { describe, expect, it } from "vitest";
import { findJsonError } from "./findJsonError";

describe("findJsonError", () => {
  it.each([
    ["オブジェクト", '{"a":[1,-2.5e+3,true,false,null,{}],"b":"\\u00e9\\n"}'],
    ["前後の空白", ' \r\n\t[ ] \n'],
    ["トップレベルの数値", "0"],
    ["トップレベルの文字列", '"日本語😀"'],
  ])("有効なJSON(%s)ならnullを返す", (_, input) => {
    expect(() => JSON.parse(input)).not.toThrow();
    expect(findJsonError(input)).toBeNull();
  });

  it.each([
    ["空文字", "", 1, 1, "JSONが入力されていません"],
    ["空白だけ", "  \n ", 2, 2, "JSONが入力されていません"],
    ["オブジェクトの末尾カンマ", '{"a":1,}', 1, 7, "最後の要素の後ろに余分なカンマがあります"],
    ["配列の末尾カンマ", "[1,\n]", 1, 3, "最後の要素の後ろに余分なカンマがあります"],
    ["シングルクォートの値", "['a']", 1, 2, '文字列はダブルクォート(")で囲む必要があります'],
    ["引用符なしのキー", "{a:1}", 1, 2, 'キーはダブルクォート(")で囲んだ文字列にする必要があります'],
    ["コロンなし", '{"a" 1}', 1, 6, "予期しない文字「1」があります"],
    ["カンマなし(オブジェクト)", '{"a":1 "b":2}', 1, 8, "カンマ(,)か閉じ括弧(})が必要です"],
    ["カンマなし(配列)", "[1 2]", 1, 4, "カンマ(,)か閉じ括弧(])が必要です"],
    ["閉じ括弧なし", '{"a":1', 1, 7, "JSONが途中で終わっています"],
    ["閉じていない文字列", '"abc', 1, 5, "文字列が閉じられていません"],
    ["文字列中の改行", '"a\nb"', 1, 3, "文字列の中に改行などの制御文字があります"],
    ["無効なエスケープ", '"\\x"', 1, 2, "無効なエスケープシーケンスです"],
    ["短い\\u", '"\\u12"', 1, 2, "\\u の後には16進数4桁が必要です"],
    ["先頭の0", "01", 1, 2, "数値の先頭に0は付けられません"],
    ["小数点の後に数字なし", "1.", 1, 3, "JSONが途中で終わっています"],
    ["プラス記号", "+1", 1, 1, "予期しない文字「+」があります"],
    ["綴り違い", "[nul]", 1, 2, "「null」の綴りが正しくありません"],
    ["途中で終わったtrue", "tru", 1, 1, "「true」の綴りが正しくありません"],
    ["数値の途中の空白", "1. 5", 1, 3, "予期しない空白があります"],
    ["数値の途中の改行", "[1e\n2]", 1, 4, "予期しない改行があります"],
    ["大文字のTrue", "True", 1, 1, "予期しない文字「T」があります"],
    ["余分な文字", "{} {}", 1, 4, "JSONの後ろに余分な文字があります"],
    ["絵文字の後のエラー", '["😀", x]', 1, 7, "予期しない文字「x」があります"],
    ["CRLFの改行", '{\r\n  "a": ?\r\n}', 2, 8, "予期しない文字「?」があります"],
  ])("%sの位置と理由を返す", (_, input, line, column, message) => {
    expect(() => JSON.parse(input)).toThrow();
    expect(findJsonError(input)).toEqual({ line, column, message });
  });
});
